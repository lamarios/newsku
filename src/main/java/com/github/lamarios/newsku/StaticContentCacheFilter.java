package com.github.lamarios.newsku;

import com.fasterxml.jackson.databind.JsonNode;
import com.fasterxml.jackson.databind.ObjectMapper;
import jakarta.servlet.FilterChain;
import jakarta.servlet.ServletException;
import jakarta.servlet.http.HttpServletRequest;
import jakarta.servlet.http.HttpServletResponse;
import java.io.IOException;
import java.io.InputStream;
import java.util.HashSet;
import java.util.Set;
import org.slf4j.Logger;
import org.slf4j.LoggerFactory;
import org.springframework.beans.factory.annotation.Value;
import org.springframework.core.io.Resource;
import org.springframework.http.HttpHeaders;
import org.springframework.stereotype.Component;
import org.springframework.web.filter.OncePerRequestFilter;

/**
 * Sets the caching headers of the Flutter web app, which is built with {@code --web-content-hash}.
 *
 * <p>Files listed as hashed in the {@code precache_manifest.json} generated by the build (e.g.
 * {@code main.dart.<hash>.wasm}) never change, so browsers can cache them forever. Everything else
 * ({@code index.html}, {@code flutter_bootstrap.js}, ...) must be revalidated so that a new deploy
 * is picked up right away. API responses are left alone.
 */
@Component
public class StaticContentCacheFilter extends OncePerRequestFilter {
  static final String IMMUTABLE = "public, max-age=31536000, immutable";
  static final String REVALIDATE = "no-cache";

  private static final Logger log = LoggerFactory.getLogger(StaticContentCacheFilter.class);

  private final Set<String> hashedPaths;

  public StaticContentCacheFilter(
      @Value("${WEB_PRECACHE_MANIFEST:classpath:public/precache_manifest.json}")
          Resource precacheManifest) {
    this.hashedPaths = readHashedPaths(precacheManifest);
  }

  private static Set<String> readHashedPaths(Resource manifest) {
    Set<String> paths = new HashSet<>();
    if (!manifest.exists()) {
      log.info("No web precache manifest found, static content will not be cached");
      return paths;
    }

    try (InputStream in = manifest.getInputStream()) {
      for (JsonNode entry : new ObjectMapper().readTree(in).path("entries")) {
        if (entry.path("urlHashed").asBoolean(false)) {
          paths.add(entry.path("url").asText());
        }
      }
    } catch (IOException e) {
      log.error("Couldn't read web precache manifest, static content will not be cached", e);
      paths.clear();
    }
    log.info("Found {} content hashed web files", paths.size());
    return paths;
  }

  @Override
  protected boolean shouldNotFilter(HttpServletRequest request) {
    String method = request.getMethod();
    return !("GET".equals(method) || "HEAD".equals(method)) || getPath(request).startsWith("api/");
  }

  @Override
  protected void doFilterInternal(
      HttpServletRequest request, HttpServletResponse response, FilterChain filterChain)
      throws ServletException, IOException {
    // Spring Security only adds its own no-store header when none is set already
    response.setHeader(
        HttpHeaders.CACHE_CONTROL, hashedPaths.contains(getPath(request)) ? IMMUTABLE : REVALIDATE);
    filterChain.doFilter(request, response);
  }

  private static String getPath(HttpServletRequest request) {
    String path = request.getRequestURI().substring(request.getContextPath().length());
    return path.startsWith("/") ? path.substring(1) : path;
  }
}
